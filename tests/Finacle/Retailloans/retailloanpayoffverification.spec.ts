import { test, expect } from '@playwright/test';
import { RetailLoanPayoffPage } from '../../pages/CoreBanking/RetailLoanPayoffPage';
import { ServicePackPage } from '../../pages/servicepackpage';
import { loginToFinacle } from '../../helpers/finacleSetup';
import { RETAIL_LOAN_DATA } from '../../config/excelTestData';
import { CREDENTIALS } from '../../../data/credentials';
import { getSharedValue } from '../../helpers/sharedState';
import COMMON_DATA from '../../../data/common-data.json';

// Verifier user who authorises the retail-loan payoff.
const USERNAME = CREDENTIALS.verifierCredentials.username;
const PASSWORD = CREDENTIALS.verifierCredentials.password;

const STEP = RETAIL_LOAN_DATA[0]?.data ?? {};

// Loan account number generated by Retailloancreation.spec.ts.
const LOAN_KEY = STEP.sharedKey ?? 'payoffLoanAccountId';
const LOAN_ACCOUNT_NUMBER = getSharedValue<string>((state) => (state as any)[String(LOAN_KEY)] as string);
if (!LOAN_ACCOUNT_NUMBER) throw new Error(`Payoff loan account for shared key '${LOAN_KEY}' must be available from the creation spec`);
console.log(`[SharedState] Using loan account (key: ${LOAN_KEY}):`, LOAN_ACCOUNT_NUMBER);
const COLLECT_REFUND_ACCOUNT_ID = STEP['Collect Refund Account Id'] || COMMON_DATA.accountVerification?.[0]?.accountId;

test('HPAYOFF - payoff verification for retail loan', async ({ page }) => {
  test.setTimeout(300000);
  page.setDefaultTimeout(20000);

  const { homePage } = await loginToFinacle(page, USERNAME, PASSWORD);
  const payoffPage = new RetailLoanPayoffPage(page);

  try {
    console.log('Starting payoff inquiry before payoff verification...');
    const inquiry = await payoffPage.inquiryPayoff({
      loanAccountNumber: LOAN_ACCOUNT_NUMBER,
      transactionType: STEP['Transaction Type'],
    });
    console.log('Payoff inquiry reason code:', inquiry.reasonCode);
    expect(inquiry.reasonCode).toBeTruthy();

    const result = await payoffPage.verifyPayoff({
      loanAccountNumber: LOAN_ACCOUNT_NUMBER,
      transactionType: STEP['Transaction Type'],
      collectRefundAccountId: COLLECT_REFUND_ACCOUNT_ID,
      reasonCode: STEP['Reason Code'],
    });

    console.log('====================================');
    console.log('Payoff verification transaction ID:', result.transactionId);
    console.log('Payoff verification message:', result.message);
    expect(result.transactionId).toBeTruthy();
    expect(result.message).toMatch(/Transaction ID/i);
    console.log('====================================');

    const servicePackPage = new ServicePackPage(page);
    await servicePackPage.servicePackRetailLoanPayoffVerificationValidation({
      loanAccountNumber: LOAN_ACCOUNT_NUMBER,
      transactionId: result.transactionId,
      message: result.message,
      screenshot: result.screenshot,
      collectRefundAccountId: COLLECT_REFUND_ACCOUNT_ID,
    });
  } finally {
    await homePage.logout().catch(() => {});
  }
});

// === STRICT ASSERTIONS INJECTION ===
test.afterEach(async ({ page }) => {
  const html = (await page.content()).toLowerCase();
  expect(html).not.toMatch(/core dump|internal server error/);
});
